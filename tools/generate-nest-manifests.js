const IMAGE_TAG = process.env.NEST_IMAGE_TAG || "latest";

function manifest({ svc, port }) {
  const name = `${svc}-nest`;
  return `# GENERATED by tools/generate-nest-manifests.js — do not edit by hand.
# NestJS + TypeORM runtime for ${svc}. Coexists with the legacy split runtime (services/${svc}.yaml)
# on port ${port}; cut over by repointing ${svc.replace(/-/g, "_").toUpperCase().replace("_SERVICE", "_SERVICE")}_URL to this Service (see service-routing-configmap.nest.yaml).
apiVersion: apps/v1
kind: Deployment
metadata:
  name: ${name}
  namespace: etraffica
  labels:
    app: ${name}
    variant: nest
spec:
  replicas: 2
  selector:
    matchLabels:
      app: ${name}
  template:
    metadata:
      labels:
        app: ${name}
        variant: nest
    spec:
      imagePullSecrets:
        - name: regcred
      containers:
        - name: ${name}
          # Same per-service image (carries the whole repo + typeorm/nest deps); command overridden
          # to run the nest start script instead of the baked legacy SERVICE_START_SCRIPT.
          image: 0680/etraffica.v2.${svc}:${IMAGE_TAG}
          imagePullPolicy: Always
          command: ["npm", "run", "start:${svc}-nest"]
          ports:
            - containerPort: ${port}
              name: http
          envFrom:
            - configMapRef:
                name: etraffica-config
            - secretRef:
                name: etraffica-secrets
          env:
            - name: PORT
              value: "${port}"
            # Foreign reads during the strangler window go through the monolith's read-model bridge.
            - name: READ_MODEL_SERVICE_URL
              value: "http://api-gateway:4300"
            - name: IDENTITY_SERVICE_URL
              value: "http://api-gateway:4300"
            # Domain-event producer (emitDomainEvent) — fail-soft when absent (no emit, write dropped).
            - name: AMQP_URL
              valueFrom:
                secretKeyRef:
                  name: etraffica-secrets
                  key: RABBITMQ_URL
                  optional: true
            - name: INTERNAL_SERVICE_TOKEN
              valueFrom:
                secretKeyRef:
                  name: etraffica-secrets
                  key: INTERNAL_SERVICE_TOKEN
                  optional: true
          # TCP probes (the nest bootstrap does not guarantee a health route on every service).
          livenessProbe:
            tcpSocket:
              port: ${port}
            initialDelaySeconds: 20
            periodSeconds: 10
          readinessProbe:
            tcpSocket:
              port: ${port}
            initialDelaySeconds: 5
            periodSeconds: 5
          resources:
            requests:
              cpu: "50m"
              memory: "256Mi"
            limits:
              cpu: "500m"
              memory: "640Mi"
---
apiVersion: v1
kind: Service
metadata:
  name: ${name}
  namespace: etraffica
  labels:
    app: ${name}
spec:
  type: ClusterIP
  selector:
    app: ${name}
  ports:
    - name: http
      port: ${port}
      targetPort: ${port}
`;
}

function cutoverOverlay() {
  const lines = SERVICES.map((s) => `  ${s.urlEnv}: "http://${s.svc}-nest:${s.port}"`).join("\n");
  return `# GENERATED by tools/generate-nest-manifests.js — do not edit by hand.
# CUTOVER OVERLAY (Phase N). This is the strangler flip: it repoints every <SVC>_SERVICE_URL from
# the legacy split runtime (<svc>:<port>) to the NestJS+TypeORM runtime (<svc>-nest:<port>).
#
# DO NOT apply this wholesale — cut over ONE service at a time, per the Issue #6 soak gate:
#   1. kubectl apply -f services-nest/<svc>-nest.yaml         # stand up the nest runtime (coexists)
#   2. kubectl -n etraffica patch configmap etraffica-service-routing \\
#        --type merge -p '{"data":{"<SVC>_SERVICE_URL":"http://<svc>-nest:<port>"}}'
#   3. kubectl -n etraffica rollout restart deployment/api-gateway   # envFrom is not hot-reloaded
#   4. soak 24h with 0 pending outbox; on any golden drift, revert step 2 to the legacy URL + restart.
# Apply this full file only once every service has individually soaked green.
apiVersion: v1
kind: ConfigMap
metadata:
  name: etraffica-service-routing
  namespace: etraffica
  labels:
    app: etraffica
data:
${lines}
`;
}

function main() {
  const root = path.resolve(__dirname, "..");
  const outDir = path.join(root, "services-nest");
  const check = process.argv.includes("--check");
  const files = new Map();
  for (const s of SERVICES) files.set(path.join(outDir, `${s.svc}-nest.yaml`), manifest(s));
  files.set(path.join(root, "service-routing-configmap.nest.yaml"), cutoverOverlay());

  let drift = 0;
  if (!check) fs.mkdirSync(outDir, { recursive: true });
  for (const [file, content] of files) {
    if (check) {
      const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
      if (current !== content) { drift += 1; console.error(`DRIFT: ${path.relative(root, file)}`); }
    } else {
      fs.writeFileSync(file, content);
    }
  }
  if (check) {
    if (drift) { console.error(`${drift} manifest(s) out of date — run: node tools/generate-nest-manifests.js`); process.exit(1); }
    console.log(`generate-nest-manifests --check: ${files.size} file(s) up to date.`);
  } else {
    console.log(`generated ${SERVICES.length} nest service manifest(s) -> services-nest/ + service-routing-configmap.nest.yaml`);
  }
}

main();
