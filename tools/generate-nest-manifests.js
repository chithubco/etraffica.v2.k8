// Generates the NestJS+TypeORM Deployment/Service manifests for the backend services
// (services-nest/*.yaml) plus the gateway's service-routing ConfigMap
// (service-routing-configmap.yaml). These nest services ARE the backend: the legacy
// split embedded runtimes (formerly services/*.yaml + apps/services/<svc>-service in the
// app repo) were deleted in the Phase-2 teardown. The gateway proxies each /api/v1/*
// route family to the owning `<svc>-nest` Service via its `<SVC>_SERVICE_URL`.
//
// legacy-parity has no nest twin: it is NOT listed here, so its URL is unset and the
// gateway embeds it in-process (SERVICE_CLUSTER_EMBED default) to serve /api/v1/legacy.
//
// The image is the service's existing per-service image (it carries the whole repo + deps);
// the container command runs the nest start script (also the image's baked default CMD, so the
// override is belt-and-suspenders). Extra env wires the service to the gateway's read-model
// bridge + identity + broker (all `optional`, fail-soft: absent -> degrades as it does locally).
//
//   node tools/generate-nest-manifests.js        # writes services-nest/*.yaml + service-routing-configmap.yaml
//   node tools/generate-nest-manifests.js --check # verify on-disk files match (CI drift guard)

