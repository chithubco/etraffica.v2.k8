const IMAGE_TAG = process.env.NEST_IMAGE_TAG || "latest";

function manifest({ svc, urlEnv, port }) {
  const name = `${svc}-nest`;
  return `# GENERATED by tools/generate-nest-manifests.js — do not edit by hand.
# NestJS + TypeORM runtime for ${svc} — the sole runtime for this service (the legacy split
# runtime was deleted). The gateway proxies its routes here via ${urlEnv} on port ${port}
# (see service-routing-configmap.yaml).
apiVersion: apps/v1
kind: Deployment
metadata:
  name: ${name}
  namespace: etraffica
  labels:
    app: ${name}
    variant: nest
spec:
  replicas: 2
  selector:
    matchLabels:
      app: ${name}
  template:
    metadata:
      labels:
        app: ${name}
        variant: nest
    spec:
      imagePullSecrets:
        - name: regcred
      containers:
        - name: ${name}
          # Same per-service image (carries the whole repo + typeorm/nest deps); command runs the
          # nest start script (also the image's baked default CMD — explicit here for clarity).
          image: 0680/etraffica.v2.${svc}:${IMAGE_TAG}
          imagePullPolicy: Always
          command: ["npm", "run", "start:${svc}-nest"]
          ports:
            - containerPort: ${port}
              name: http
          envFrom:
            - configMapRef:
                name: etraffica-config
            - secretRef:
                name: etraffica-secrets
          env:
            - name: PORT
              value: "${port}"
            # Foreign reads go through the gateway's read-model bridge.
            - name: READ_MODEL_SERVICE_URL
              value: "http://api-gateway:4300"
            - name: IDENTITY_SERVICE_URL
              value: "http://api-gateway:4300"
            # payments-media forwards processed provider callbacks to operations (the
            # certification cross-service join); harmless for the other services.
            - name: OPERATIONS_SERVICE_URL
              value: "http://operations-service-nest:4321"
            # Domain-event producer (emitDomainEvent) — fail-soft when absent (no emit, write dropped).
            - name: AMQP_URL
              valueFrom:
                secretKeyRef:
                  name: etraffica-secrets
                  key: RABBITMQ_URL
                  optional: true
            - name: INTERNAL_SERVICE_TOKEN
              valueFrom:
                secretKeyRef:
                  name: etraffica-secrets
                  key: INTERNAL_SERVICE_TOKEN
                  optional: true
          # TCP probes (the nest bootstrap does not guarantee a health route on every service).
          livenessProbe:
            tcpSocket:
              port: ${port}
            initialDelaySeconds: 20
            periodSeconds: 10
          readinessProbe:
            tcpSocket:
              port: ${port}
            initialDelaySeconds: 5
            periodSeconds: 5
          resources:
            requests:
              cpu: "50m"
              memory: "256Mi"
            limits:
              cpu: "500m"
              memory: "640Mi"
---
apiVersion: v1
kind: Service
metadata:
  name: ${name}
  namespace: etraffica
  labels:
    app: ${name}
spec:
  type: ClusterIP
  selector:
    app: ${name}
  ports:
    - name: http
      port: ${port}
      targetPort: ${port}
`;
}

function routingConfigMap() {
  const lines = SERVICES.map((s) => `  ${s.urlEnv}: "http://${s.svc}-nest:${s.port}"`).join("\n");
  return `# GENERATED by tools/generate-nest-manifests.js — do not edit by hand.
# Consumed ONLY by the api-gateway. Each <SVC>_SERVICE_URL tells the gateway to PROXY that
# service's /api/v1/* routes to the owning NestJS+TypeORM runtime (<svc>-nest:<port>). The
# host:port here must match the corresponding Service in services-nest/<svc>-nest.yaml.
# (apps/services/common/service-cluster.ts)
#
# legacy-parity is intentionally absent: with no URL set, the gateway embeds it in-process to
# serve /api/v1/legacy (it has no nest twin).
apiVersion: v1
kind: ConfigMap
metadata:
  name: etraffica-service-routing
  namespace: etraffica
  labels:
    app: etraffica
data:
${lines}
`;
}

function main() {
  const root = path.resolve(__dirname, "..");
  const outDir = path.join(root, "services-nest");
  const check = process.argv.includes("--check");
  const files = new Map();
  for (const s of SERVICES) files.set(path.join(outDir, `${s.svc}-nest.yaml`), manifest(s));
  files.set(path.join(root, "service-routing-configmap.yaml"), routingConfigMap());

  let drift = 0;
  if (!check) fs.mkdirSync(outDir, { recursive: true });
  for (const [file, content] of files) {
    if (check) {
      const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
      if (current !== content) { drift += 1; console.error(`DRIFT: ${path.relative(root, file)}`); }
    } else {
      fs.writeFileSync(file, content);
    }
  }
  if (check) {
    if (drift) { console.error(`${drift} manifest(s) out of date — run: node tools/generate-nest-manifests.js`); process.exit(1); }
    console.log(`generate-nest-manifests --check: ${files.size} file(s) up to date.`);
  } else {
    console.log(`generated ${SERVICES.length} nest service manifest(s) -> services-nest/ + service-routing-configmap.yaml`);
  }
}

main();
