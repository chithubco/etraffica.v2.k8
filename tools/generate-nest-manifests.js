// Generates the NestJS+TypeORM ("-nest") Deployment/Service manifests for the migrated
// services, plus the cutover ConfigMap overlay. Each nest service coexists with its legacy
// split-runtime counterpart under a distinct `<svc>-nest` name on the SAME port; cutover is a
// per-service repoint of `<SVC>_SERVICE_URL` from `<svc>:<port>` to `<svc>-nest:<port>` in the
// service-routing ConfigMap (service-routing-configmap.nest.yaml), then a gateway rollout.
//
// The image is the service's existing per-service image (it carries the whole repo + deps), with
// the container command OVERRIDDEN to run the nest start script — so no new CI image is required.
// Extra env wires the migrated service to the still-legacy read-model bridge + identity + broker
// (all `optional`, fail-soft: absent -> the service just degrades exactly as it does locally).
//
//   node tools/generate-nest-manifests.js        # writes services-nest/*.yaml + the cutover overlay
//   node tools/generate-nest-manifests.js --check # verify on-disk files match (CI drift guard)

